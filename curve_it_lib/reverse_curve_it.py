#!/usr/bin/env python3
"""Invert Curve It's group transforms to sample the mapped centerline.

For each group, fit a proper rotation and translation from template coordinates
expressed about the *template axis*, not about the group's centroid. The image
of that axis point is a centerline sample. Phase and frame holonomy are absorbed
by the fitted rotation; per-atom axial twist must be applied before fitting.
Only occupied portions of the path are observable. Original vertices, scaling
before embedding, unused endpoints, and multiple wraps cannot in general be
deduced from two PDB files.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import os
from pathlib import Path
import re
import sys
from typing import List, Optional

import numpy as np

# Also support `python curve_it_lib/reverse_curve_it.py` from another folder.
if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import curve_it


VERSION = "1.0.0"


@dataclass
class RecoveryResult:
    points: np.ndarray
    # One station per recovered point; fit errors/sizes retain one per group.
    stations: np.ndarray
    group_rmsd: np.ndarray
    group_sizes: np.ndarray
    axis_length: float
    path_type: str
    twist: float
    matched_atoms: int
    missing_atoms: int
    extra_atoms: int
    skipped_groups: int
    notes: List[str]

    @property
    def rmsd(self) -> float:
        return float(np.sqrt(np.average(self.group_rmsd ** 2,
                                        weights=self.group_sizes)))


def _atom_key(atom):
    # Serial numbers and record order may change when a PDB is saved again.
    return (atom.chain_id, atom.res_seq, atom.i_code, atom.res_name.upper(),
            atom.atom_name_norm, atom.line[16:17].strip())


def _atom_label(key) -> str:
    chain, seq, insertion, residue, name, alt = key
    return f"{chain or '_'}:{seq}{insertion}:{residue}:{name}" + (
        f" (altloc {alt})" if alt else "")


def _read_atoms(text: str, label: str):
    """Keep the forward parser, but reject records it would silently skip."""
    models = sum(line[:6].strip() == "MODEL" for line in text.splitlines())
    if models > 1:
        raise ValueError(f"{label}: multiple MODEL records; supply one model per PDB.")
    for number, line in enumerate(text.splitlines(), 1):
        if line[:6].strip() not in ("ATOM", "HETATM"):
            continue
        try:
            coord = [float(line[a:b]) for a, b in ((30, 38), (38, 46), (46, 54))]
            int(line[22:26])
            valid = len(line) >= 54 and np.isfinite(coord).all()
        except ValueError:
            valid = False
        if not valid:
            raise ValueError(f"{label}: invalid atom coordinates or residue number "
                             f"on line {number}.")
    atoms = curve_it.parse_pdb_atoms(text)
    if not atoms:
        raise ValueError(f"{label}: no ATOM/HETATM coordinates found.")
    index = {}
    for i, atom in enumerate(atoms):
        key = _atom_key(atom)
        if key in index:
            raise ValueError(f"{label}: ambiguous duplicate atom {_atom_label(key)}. "
                             "Use unique chain/residue/atom/alternate-location IDs.")
        index[key] = i
    return atoms, index


def _mapping_metadata(text: str) -> dict:
    # Curve It prepends its newest generation block. Stop at any older block
    # so stale options cannot supply a missing option in the newest generation.
    lines = []
    started = False
    for line in text.splitlines():
        if not line.startswith("REMARK 900 "):
            continue
        body = line[11:]
        if body.startswith("Generated by curve_it "):
            if started:
                break
            started = True
        if started:
            lines.append(body)
    joined = " ".join(lines)
    return dict(re.findall(r"\b(path_type|twist)\s*=\s*([^;\s]+)", joined))


def _fit_axis_point(source: np.ndarray, target: np.ndarray):
    """Return the transformed origin and residual, or None for a line/point."""
    if len(source) < 3:
        return None
    xmean, ymean = source.mean(axis=0), target.mean(axis=0)
    x, y = source - xmean, target - ymean
    for centered in (x, y):
        singular = np.linalg.svd(centered, compute_uv=False)
        if singular[1] <= max(1e-8, singular[0] * 1e-6):
            return None
    u, _, vt = np.linalg.svd(x.T @ y)
    correction = np.eye(3)
    correction[2, 2] = 1.0 if np.linalg.det(u @ vt) >= 0 else -1.0
    rotation = u @ correction @ vt
    origin = ymean - xmean @ rotation
    rmsd = float(np.sqrt(np.mean(np.sum((source @ rotation + origin - target) ** 2,
                                       axis=1))))
    return origin, rmsd


def recover_curve(curved_text: str, template_text: str,
                  path_type: str = "auto", twist: Optional[float] = None,
                  allow_missing_atoms: bool = False) -> RecoveryResult:
    """Recover axis samples in the curved PDB's coordinates, in Angstrom.

    Atom identity, PCA, group membership, and group stations all come from the
    complete straight template. Missing curved atoms can be allowed explicitly;
    this never recomputes the axis or group centers on the surviving subset.
    Samples follow increasing template principal-axis coordinate, matching the
    forward mapper's traversal even for antiparallel strands.
    """
    template, source_index = _read_atoms(template_text, "Straight template")
    curved, target_index = _read_atoms(curved_text, "Curved model")
    missing = source_index.keys() - target_index.keys()
    extra = target_index.keys() - source_index.keys()
    if (missing or extra) and not allow_missing_atoms:
        detail = "; ".join(
            f"{len(keys)} {name} (e.g. {_atom_label(sorted(keys)[0])})"
            for name, keys in (("missing from curved model", missing),
                               ("extra in curved model", extra)) if keys)
        raise ValueError(f"Atom identities do not match: {detail}. Use the original "
                         "straight template and preserve chain/residue/atom IDs. "
                         "--allow-missing-atoms fits only shared atoms explicitly.")

    metadata = _mapping_metadata(curved_text)
    notes = []
    if path_type == "auto":
        path_type = metadata.get("path_type", "open").rstrip(".")
        if "path_type" not in metadata:
            notes.append("No Curve It path metadata: treating the curve as open; "
                         "choose closed if the model follows a loop.")
    if path_type not in ("open", "closed"):
        raise ValueError("path_type must be auto, open, or closed.")
    if twist is None:
        twist = float(metadata.get("twist", "0"))
        if "twist" not in metadata:
            notes.append("No Curve It twist metadata: assuming 0 degrees; "
                         "supply --twist if extra axial twist was used.")
    twist = float(twist)
    if not np.isfinite(twist):
        raise ValueError("Twist must be a finite number of degrees.")

    coords = np.array([atom.coord for atom in template])
    _, _, _, s, local = curve_it.compute_helix_local_coords(coords)
    s_min = float(s.min())
    axis_length = float(np.ptp(s))
    if axis_length <= 1e-6:
        raise ValueError("Straight template axis length is too small or degenerate.")
    groups, group_s = curve_it.build_atom_groups(template, s)

    # The forward mapper twists *each atom* before applying the common group
    # frame. A global phase is a common rotation and needs no separate option.
    phi = np.deg2rad(twist) * (s - s_min) / axis_length
    x, y = local[:, 0].copy(), local[:, 1].copy()
    local[:, 0] = np.cos(phi) * x - np.sin(phi) * y
    local[:, 1] = np.sin(phi) * x + np.cos(phi) * y

    fitted = []
    skipped = 0
    for indices, station in zip(groups, group_s):
        shared = [i for i in indices if _atom_key(template[i]) in target_index]
        source = local[shared].copy()
        source[:, 2] = s[shared] - station
        target = np.array([curved[target_index[_atom_key(template[i])]].coord
                           for i in shared]).reshape(-1, 3)
        fit = _fit_axis_point(source, target)
        if fit is None:
            skipped += 1
            continue
        point, rmsd = fit
        fitted.append((float(station - s_min), point, rmsd, len(shared)))

    if len(fitted) < 2:
        raise ValueError("Need at least two groups with three noncollinear matched "
                         "atoms each to recover a curve. A CA-only or P-only model "
                         "does not determine local axis positions.")
    fitted.sort(key=lambda row: row[0])
    stations = np.array([row[0] for row in fitted])
    if np.ptp(stations) <= 1e-6:
        raise ValueError("Fitted groups occupy only one template axis station.")
    raw = np.array([row[1] for row in fitted])
    errors = np.array([row[2] for row in fitted])
    sizes = np.array([row[3] for row in fitted])

    # Independent groups at the same station sample the same path point. Merge
    # only numerical ties, never neighbouring stations or nearby spatial points
    # (which could be crossings). Atom counts weight the independent estimates.
    cuts = np.r_[0, np.flatnonzero(np.diff(stations) > 1e-7) + 1, len(stations)]
    points = np.array([np.average(raw[a:b], axis=0, weights=sizes[a:b])
                       for a, b in zip(cuts[:-1], cuts[1:])])
    stations = np.array([np.average(stations[a:b], weights=sizes[a:b])
                         for a, b in zip(cuts[:-1], cuts[1:])])
    # Curve It's XYZ convention omits the duplicate endpoint on closed curves.
    if path_type == "closed" and np.linalg.norm(points[-1] - points[0]) < 1e-6:
        points = points[:-1]
        stations = stations[:-1]
    # Consecutive rounded-identical points would create zero-length segments.
    rounded = np.round(points, 6)
    keep = np.r_[True, np.any(np.diff(rounded, axis=0) != 0, axis=1)]
    points = points[keep]
    stations = stations[keep]
    if (path_type == "closed" and len(points) > 1
            and np.array_equal(np.round(points[-1], 6), np.round(points[0], 6))):
        points = points[:-1]
        stations = stations[:-1]
    if len(points) < (3 if path_type == "closed" else 2):
        raise ValueError("Too few distinct recovered points for the selected path type.")
    if skipped:
        notes.append(f"Skipped {skipped} groups with fewer than three matched atoms "
                     "or collinear geometry.")
    if missing or extra:
        notes.append(f"Used shared atom IDs: {len(missing)} template atoms missing; "
                     f"{len(extra)} extra curved atoms ignored.")
    if errors.max() > 0.1:
        notes.append("Some group fits exceed 0.1 A RMSD. Local deformation, a wrong "
                     "template, or an incorrect twist can bias the recovered axis; "
                     "small fit errors alone do not guarantee axis accuracy.")
    notes.append("Samples cover the occupied path, ordered along the template axis. "
                 "Unsampled endpoints, corners and gaps are not reconstructed. "
                 "Multiple wraps remain multiple traversals in the output.")
    return RecoveryResult(points, stations, errors, sizes, axis_length, path_type,
                          twist, len(source_index) - len(missing), len(missing),
                          len(extra), skipped, notes)


def default_output_path(curved_path: str) -> str:
    path = Path(curved_path).expanduser()
    return str(path.with_name(path.stem + "_curve.xyz"))


def describe(result: RecoveryResult, points: Optional[np.ndarray] = None) -> str:
    points = result.points if points is None else points
    line = np.vstack([points, points[:1]]) if result.path_type == "closed" else points
    length = np.linalg.norm(np.diff(line, axis=0), axis=1).sum()
    return "\n".join([
        f"Reverse Curve It {VERSION}",
        f"Matched atoms: {result.matched_atoms}",
        f"Fitted groups: {len(result.group_rmsd)}; skipped: {result.skipped_groups}",
        f"Group fit RMSD: {result.rmsd:.6f} A; "
        f"maximum: {result.group_rmsd.max():.6f} A",
        f"Template axis length: {result.axis_length:.6f} A",
        f"Sampled template stations: {result.stations[0]:.6f} to "
        f"{result.stations[-1]:.6f} A",
        f"Path type: {result.path_type}; extra twist: {result.twist:g} deg",
        f"Output: {len(points)} points; polyline length: {length:.6f} A",
        "Coordinates are in the curved PDB's frame, in Angstrom.",
    ] + result.notes)


def recover_files(curved_path: str, template_path: str, output_path: Optional[str] = None,
                  path_type: str = "auto", twist: Optional[float] = None,
                  points: Optional[int] = None, allow_missing_atoms: bool = False):
    curved = Path(curved_path).expanduser().resolve()
    template = Path(template_path).expanduser().resolve()
    output = Path(output_path or default_output_path(str(curved))).expanduser().resolve()
    for source in (curved, template):
        if output == source or (output.exists() and os.path.samefile(output, source)):
            raise ValueError("Output XYZ must not overwrite either input PDB.")
    result = recover_curve(curved.read_text(), template.read_text(), path_type,
                           twist, allow_missing_atoms)
    out_points = result.points
    if points is not None:
        out_points = curve_it.apply_curve_interpolation(
            out_points, interp_mode="n", interp_n=points,
            closed=result.path_type == "closed")
    # Check what is actually serialized, including the implicit closing edge.
    rounded = np.round(out_points, 6)
    line = np.vstack([rounded, rounded[:1]]) if result.path_type == "closed" else rounded
    if np.any(np.all(np.diff(line, axis=0) == 0, axis=1)):
        raise ValueError("Output sampling creates duplicate consecutive points at "
                         "six decimals; request fewer points.")
    report = describe(result, out_points)
    with output.open("w") as handle:
        handle.write(f"# Curved PDB: {curved}\n# Straight template: {template}\n")
        for row in report.splitlines():
            handle.write(f"# {row}\n")
        np.savetxt(handle, out_points, fmt="%.6f")
    return result, str(output), report


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Recover a sampled curve XYZ from a curved PDB and the original "
                    "straight template used by Curve It. Coordinates are in Angstrom.")
    parser.add_argument("curved_pdb", nargs="?", help="Final curved PDB model.")
    parser.add_argument("template_pdb", nargs="?", help="Original straight PDB template.")
    parser.add_argument("-o", "--output", help="Output XYZ (default: <curved>_curve.xyz).")
    parser.add_argument("--path-type", choices=("auto", "open", "closed"), default="auto",
                        help="Auto reads Curve It REMARKs, otherwise open. XYZ does not "
                             "store closure; select this path type when reloading it.")
    parser.add_argument("--twist", type=float, default=None,
                        help="Extra axial twist used by Curve It, in degrees. Default: "
                             "read REMARKs, otherwise 0. Global phase is inferred.")
    parser.add_argument("-n", "--points", type=int,
                        help="Optionally resample to this many points by arc length, "
                             "preserving corners. Default: keep recovered samples.")
    parser.add_argument("--allow-missing-atoms", action="store_true",
                        help="Fit shared atom IDs, ignore extra atoms. Axis and group "
                             "centers still use the complete straight template.")
    parser.add_argument("--gui", action="store_true", help="Open the tool window.")
    parser.add_argument("--version", action="version", version=f"Reverse Curve It {VERSION}")
    return parser


def run_gui(args=None) -> int:
    import tkinter as tk
    from tkinter import filedialog, messagebox, ttk

    args = args or build_parser().parse_args([])
    root = tk.Tk()
    root.title("Reverse Curve It - recover a curve from a PDB model")
    root.columnconfigure(1, weight=1)
    root.rowconfigure(9, weight=1)
    values = {
        "curved": tk.StringVar(value=args.curved_pdb or ""),
        "template": tk.StringVar(value=args.template_pdb or ""),
        "output": tk.StringVar(value=args.output or (
            default_output_path(args.curved_pdb) if args.curved_pdb else "")),
        "path": tk.StringVar(value=args.path_type),
        "twist": tk.StringVar(value="auto" if args.twist is None else str(args.twist)),
        "points": tk.StringVar(value="keep" if args.points is None else str(args.points)),
        "missing": tk.BooleanVar(value=args.allow_missing_atoms),
    }
    help_text = {
        "curved": "The final curved PDB, including a model saved after refinement. "
                  "Atom IDs must correspond to the straight template. Supply one model.",
        "template": "The original straight PDB used to make this model. Its complete "
                    "atom set defines Curve It's axis and group centers. A different "
                    "template can bias the recovered curve even with small fit errors.",
        "output": "Write plain x y z rows in Angstrom, in the curved model's coordinate "
                  "frame. The default is <curved>_curve.xyz. Comments record the fit.",
        "path": "Auto reads Curve It's path_type REMARK, otherwise uses open. Choose "
                "closed for a loop; its first point is not repeated. When loading the "
                "XYZ into Curve It, select the same path type there.",
        "twist": "Extra axial twist in degrees used to make the curved model. Auto "
                 "reads Curve It's REMARK, otherwise assumes 0. For example, enter 360 "
                 "if Curve It applied one extra turn. Phase needs no input.",
        "points": "Keep preserves recovered group samples. Enter a whole number, such "
                  "as 400, to resample by arc length while preserving corners. This "
                  "does not recover any missing detail or smooth a refined model.",
        "missing": "By default the atom IDs must match exactly. Tick this if the curved "
                   "PDB has lost atoms or gained waters, for example. Shared atoms "
                   "are fitted; each usable group still needs three noncollinear atoms. "
                   "The complete straight template is always needed.",
    }

    def help_button(key, row):
        ttk.Button(root, text="?", width=2,
                   command=lambda: messagebox.showinfo("Reverse Curve It", help_text[key],
                                                       parent=root)).grid(
                       row=row, column=3, padx=(0, 10), pady=4)

    ttk.Label(root, text="Recover the model's centerline using its original straight template.",
              wraplength=700).grid(row=0, column=0, columnspan=4, sticky="w", padx=10, pady=10)
    for row, (key, label) in enumerate((("curved", "Curved PDB"),
                                        ("template", "Straight template PDB"),
                                        ("output", "Output curve XYZ")), 1):
        ttk.Label(root, text=label).grid(row=row, column=0, sticky="w", padx=10)
        ttk.Entry(root, textvariable=values[key], width=60).grid(
            row=row, column=1, sticky="ew", pady=4)

        def browse(key=key):
            if key == "output":
                selected = filedialog.asksaveasfilename(parent=root, defaultextension=".xyz",
                                                        filetypes=[("Curve XYZ", "*.xyz")])
            else:
                selected = filedialog.askopenfilename(parent=root,
                    title="Select " + ("curved PDB" if key == "curved" else "straight template PDB"),
                    filetypes=[("PDB files", "*.pdb *.ent"), ("All files", "*.*")])
            if selected:
                old_default = (default_output_path(values["curved"].get())
                               if values["curved"].get() else "")
                if key == "curved" and values["output"].get() in ("", old_default):
                    values["output"].set(default_output_path(selected))
                values[key].set(selected)

        ttk.Button(root, text="Browse...", command=browse).grid(row=row, column=2, padx=6)
        help_button(key, row)
    for row, key, label in ((4, "path", "Path type"), (5, "twist", "Extra twist (deg)"),
                            (6, "points", "Output points")):
        ttk.Label(root, text=label).grid(row=row, column=0, sticky="w", padx=10)
        if key == "path":
            widget = ttk.Combobox(root, textvariable=values[key], state="readonly",
                                  values=("auto", "open", "closed"), width=12)
        else:
            widget = ttk.Entry(root, textvariable=values[key], width=14)
        widget.grid(row=row, column=1, sticky="w", pady=4)
        help_button(key, row)
    ttk.Checkbutton(root, text="Allow missing / extra atoms (fit shared IDs)",
                    variable=values["missing"]).grid(row=7, column=0, columnspan=3,
                                                     sticky="w", padx=10, pady=4)
    help_button("missing", 7)
    log = tk.Text(root, width=94, height=15, wrap="word", state="disabled")
    log.grid(row=9, column=0, columnspan=4, sticky="nsew", padx=10, pady=(0, 10))
    status = tk.StringVar(value="Ready.")

    def generate():
        try:
            curved, template = (values[key].get().strip() for key in ("curved", "template"))
            if not curved or not template:
                raise ValueError("Select both the curved PDB and its straight template.")
            twist_text = values["twist"].get().strip().lower()
            point_text = values["points"].get().strip().lower()
            status.set("Recovering curve...")
            root.update_idletasks()
            _, output, report = recover_files(
                curved, template, values["output"].get().strip() or None,
                values["path"].get(),
                None if twist_text in ("", "auto") else float(twist_text),
                None if point_text in ("", "keep") else int(point_text),
                values["missing"].get())
            values["output"].set(output)
            log.configure(state="normal")
            log.delete("1.0", "end")
            log.insert("end", report + "\nWrote: " + output + "\n")
            log.configure(state="disabled")
            status.set("Curve written.")
        except (OSError, ValueError) as exc:
            status.set("Recovery failed.")
            messagebox.showerror("Reverse Curve It", str(exc), parent=root)

    bar = ttk.Frame(root)
    bar.grid(row=8, column=0, columnspan=4, sticky="ew", padx=10, pady=8)
    ttk.Button(bar, text="Recover curve", command=generate).pack(side="left")
    ttk.Label(bar, textvariable=status).pack(side="left", padx=12)
    root.mainloop()
    return 0


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    args = parser.parse_args(argv)
    if not argv or args.gui:
        return run_gui(args)
    if not args.curved_pdb or not args.template_pdb:
        parser.error("provide curved_pdb and template_pdb, or use --gui")
    try:
        _, output, report = recover_files(
            args.curved_pdb, args.template_pdb, args.output, args.path_type,
            args.twist, args.points, args.allow_missing_atoms)
        print(report)
        print(f"Wrote: {output}")
        return 0
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
